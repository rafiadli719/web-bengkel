    GROUP BY A.TAHUN, A.SIKLUS, A.STS

    UNION ALL

    SELECT 
        A.TAHUN, 
        A.SIKLUS, 
        SUM(A.FREK) AS TOT_FREK, 
        SUM(A.QTY) AS TOT_QTY, 
