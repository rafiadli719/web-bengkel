SELECT A.NamaPelanggan, A.DOMISILI, Count(A.NoPelanggan) AS JUM_MOTOR, Sum(B.JUMLAH) AS TOT_DATANG, Sum(B.TOTAL) AS TOTAL_NILAI, Round(Sum(B.TOTAL)/Sum(B.JUMLAH)) AS RATA2_NILAI, Min(B.AWAL) AS AWAL, Max(B.AKHIR) AS AKHIR, Max(B.DATANG_BERIKUTNYA) AS DATANG_BERIKUTNYA, CURDATE()-Min(B.AWAL) AS LAMA_PELANGGAN, CURDATE()-Max(B.AKHIR) AS LAMA_TDK_DATANG, `AKHIR`+(30*(-FLOOR(-((CURDATE()-`AKHIR`)/30)))) AS TIAP_30HARI, A.Telephone
FROM NOMOR_WA__DOMISILI_NOPOLISI AS A LEFT JOIN REKAP_KONSUMEN_DATANGBERIKUTNYA AS B ON A.NoPelanggan = B.NOPOLISI
GROUP BY A.NamaPelanggan, A.Telephone, A.DOMISILI
;

