DROP VIEW IF EXISTS `GANTI_OLI_TERAKHIR`;
CREATE OR REPLACE VIEW `GANTI_OLI_TERAKHIR` AS
SELECT A.*, IF(RATA2_GANTI <= 45, 30, 60) AS GANTI_TIAP
FROM (SELECT NoPolisi, COUNT(TGGL) AS JUM, MIN(TGGL) AS AWAL, MAX(TGGL) AS AKHIR, ROUND((MAX(TGGL) - MIN(TGGL)) / IF(COUNT(TGGL)=1,1,(COUNT(TGGL)-1))) AS RATA2_GANTI, CURDATE() - MAX(TGGL) AS AKHIR_HARI_INI FROM (SELECT * FROM GANTI_OLI_DATA)  AS A GROUP BY NoPolisi)  AS A
;

DROP VIEW IF EXISTS `HARI_KONSUMEN_DATANG`;
CREATE OR REPLACE VIEW `HARI_KONSUMEN_DATANG` AS
SELECT NOPOLISI, SUM(WEEKEND) AS JUM_WEEKEND, SUM(WEEKDAY) AS JUM_WEEKDAY, IF( SUM(WEEKEND) >= SUM(WEEKDAY) , 'WEEKEND', 'WEEKDAY') AS TIPE
FROM (SELECT NoPolisi, IF( WEEKDAY(Tanggal) IN (1,7), 1, 0) AS WEEKEND, IF( WEEKDAY(Tanggal) NOT IN (1,7), 1, 0) AS WEEKDAY FROM GABUNG_SERVICE_HEADER WHERE NoPolisi IS NOT NULL)  AS A
